package pe.gob.munihuamanga.licencias.common.enums;

/**
 * Modalidad de vigencia de la Licencia de Funcionamiento (Ley N° 28976 / TUO D.S. N° 046-2017-PCM).
 */
public enum TipoVigenciaLicencia {
    /**
     * Vigencia indeterminada (regla general legal - Art. 11 Ley 28976).
     */
    INDETERMINADA,

    /**
     * Vigencia temporal (cuando sea solicitada expresamente por el administrado o para actividades temporales).
     */
    TEMPORAL
}
